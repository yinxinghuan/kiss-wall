export function t(key: string, vars?: { n?: number | string }): string {
  let s = STRINGS[LOCALE][key] ?? STRINGS.en[key] ?? key;
  if (vars?.n != null) s = s.replace('{n}', String(vars.n));
  return s;
}

export function getLocale(): Locale {
  return LOCALE;
}
