type Locale = 'zh' | 'en';

function detectLocale(): Locale {
  try {
    const override = localStorage.getItem('kiss-wall-locale');
    if (override === 'en' || override === 'zh') return override;
  } catch { /* private mode */ }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

